import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const read = (file) => readFile(new URL(file, root), 'utf8');

// These static modules intentionally have no network or runtime dependencies.
// Rewrite the workbench's one engine import so the same ESM also runs in srcDoc.
const [html, style, app, engine, entry] = await Promise.all([
  'workbench.html', 'workbench.css', 'workbench.mjs', 'engine.mjs', 'client-source.js'
].map(read));
const asModule = (source) => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
function replaceOne(source, search, value) {
  const match = source.match(search);
  if (!match || source.indexOf(match[0]) !== source.lastIndexOf(match[0])) {
    throw new Error('Expected one resource reference in workbench source: ' + search);
  }
  return source.replace(search, () => value);
}
const js = replaceOne(app, /from\s+['"]\.\/engine\.mjs['"]/, 'from "' + asModule(engine) + '"');
const policy = [
  "default-src 'none'", "script-src data:", "style-src 'unsafe-inline'", "img-src data:",
  "base-uri 'none'", "form-action 'none'"
].join('; ');
let page = replaceOne(html, /<head>/, '<head>\n<meta http-equiv="Content-Security-Policy" content="' + policy + '">');
page = replaceOne(page, /<link\b[^>]*href=["']\.\/workbench\.css["'][^>]*>/, '<style>' + style + '</style>');
page = replaceOne(page, /<script\b[^>]*src=["']\.\/workbench\.mjs["'][^>]*><\/script>/,
  '<script type="module" src="' + asModule(js) + '"></script>');
const bundle = replaceOne(entry, /'__DSH_WORKBENCH_DOCUMENT__'/, JSON.stringify(page));
await writeFile(new URL('./client.js', import.meta.url), '// Generated by build.mjs\n' + bundle);
